/** JEE uses Physics/Chemistry/Maths; NEET uses its own NCERT-ordered Physics and Chemistry banks plus Biology. */
export type Subject = 'Physics' | 'Chemistry' | 'Maths' | 'NEET Physics' | 'NEET Chemistry' | 'Biology';
/** The student's track: a school class or an entrance exam. */
export type Exam = 'C8' | 'C9' | 'C10' | 'C11' | 'C12' | 'JEE' | 'NEET';
export type Board = 'Kerala SCERT' | 'CBSE' | 'ICSE';
export const BOARDS: Board[] = ['Kerala SCERT', 'CBSE', 'ICSE'];
export type Difficulty = 'Easy' | 'Moderate' | 'Hard';

export type Question = {
  id: string;
  subject: Subject;
  /** index into SYLLABUS[subject] */
  chapter: number;
  /** may contain [[img:<hash>]] tokens */
  text: string;
  /** 'mcq' has 4 options and `answer` index; 'numerical' has `numAnswer` */
  type: 'mcq' | 'numerical';
  options: string[];
  answer: number;
  numAnswer?: string;
  explanation: string;
  /** true when the solution was written by AI from the answer key */
  aiSolution?: boolean;
  difficulty: Difficulty;
  topic: string;
};

/** A student's response: option index (MCQ), typed number (numerical), or -1 for skipped. */
export type Answer = number | string;

