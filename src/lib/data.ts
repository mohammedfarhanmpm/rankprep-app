/** JEE chapter indices feeding a NEET chapter. */
function jeeSources(subject: Subject, chapter: number): { subject: 'Physics' | 'Chemistry'; chapter: number }[] {
  const jee = JEE_OF[subject];
  if (!jee) return [];
  const names = JEE_FOR_NEET[subject as 'NEET Physics' | 'NEET Chemistry'][BANK_CHAPTERS[subject as BankSubject][chapter]?.name] ?? [];
  return names.map((n) => ({ subject: jee, chapter: BANK_CHAPTERS[jee].findIndex((c) => c.name === n) })).filter((x) => x.chapter >= 0);
}

/** Questions of one chapter (loaded on first use, then cached). NEET chapters also include matching JEE MCQs. */
export function chapterQuestions(subject: Subject, chapter: number): Question[] {
  const own = ownChapterQuestions(subject, chapter);
  const extra = jeeSources(subject, chapter);
  if (!extra.length) return own;
  const key = `neet+${subject}${chapter}`;
  let all = cache.get(key);
  if (!all) {
    const jee = extra.flatMap((x) => ownChapterQuestions(x.subject, x.chapter).filter((q) => q.type === 'mcq').map((q) => ({ ...q, subject, chapter })));
    all = [...own, ...jee];
    cache.set(key, all);
  }
  return all;
}

function ownChapterQuestions(subject: Subject, chapter: number): Question[] {
  const meta = BANK_CHAPTERS[subject as BankSubject]?.[chapter];
  if (!meta) return [];
  let qs = cache.get(meta.code);
  if (!qs) {
    qs = LOADERS[meta.code]().map((r) => ({
      id: r.i, subject, chapter, text: r.t, type: r.o ? 'mcq' : 'numerical', options: r.o ?? [], answer: r.a ?? -1, numAnswer: r.n,
      explanation: r.s, aiSolution: r.x === 1, difficulty: DIFF[r.d], topic: r.p,
    }));
    cache.set(meta.code, qs);
  }
  return qs;
}

export function subjectQuestions(subject: Subject): Question[] {
  return SYLLABUS[subject].flatMap((_, i) => chapterQuestions(subject, i));
}

// chapter code (e.g. "NP07") -> [subject, chapter index]
const CODE_INDEX: Record<string, [BankSubject, number]> = {};
BANK_SUBJECTS.forEach((s) => BANK_CHAPTERS[s].forEach((c, i) => (CODE_INDEX[c.code] = [s, i])));

/** Look up a question by id, e.g. "NP07-0042" (used by the mistake notebook). */
export function getQuestion(id: string): Question | undefined {
  const hit = CODE_INDEX[id.split('-')[0]];
  return hit ? chapterQuestions(hit[0], hit[1]).find((q) => q.id === id) : undefined;
}

/** Subject name without the exam prefix, for compact labels ("NEET Physics" -> "Physics"). */
export const subjectLabel = (s: Subject) => s.replace(/^NEET /, '');

export function questionCount(subject: Subject, chapter: number): number {
  const own = BANK_CHAPTERS[subject as BankSubject]?.[chapter]?.count ?? 0;
  return own + jeeSources(subject, chapter).reduce((n, x) => n + BANK_CHAPTERS[x.subject][x.chapter].mcq, 0);
}

export function subjectCount(subject: Subject, exam?: Exam): number {
  const chs = exam ? examChapters(exam, subject) : SYLLABUS[subject].map((_, i) => i);
  return chs.reduce((n, i) => n + questionCount(subject, i), 0);
}

function shuffle<T>(a: T[]): T[] {
  const r = [...a];
  for (let i = r.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [r[i], r[j]] = [r[j], r[i]];
  }
  return r;
}

/** Random sample of n questions from a subject without loading every chapter. */
function sampleSubject(exam: Exam, subject: Subject, n: number, diff?: Difficulty): Question[] {
  const out: Question[] = [];
  const chapters = shuffle(examChapters(exam, subject).filter((i) => questionCount(subject, i) > 0));
  for (let k = 0; out.length < n && k < chapters.length * 3; k++) {
    const pool = chapterQuestions(subject, chapters[k % chapters.length]).filter((q) => !diff || q.difficulty === diff);
    const q = pool[Math.floor(Math.random() * pool.length)];
    if (q && !out.includes(q)) out.push(q);
  }
  return out;
}

export type TestSpec =
  | { kind: 'mixed' }
  | { kind: 'quick' }
  | { kind: 'subject'; subject: Subject }
  | { kind: 'chapter'; subject: Subject; chapter: number }
  | { kind: 'ids'; ids: string[]; label: string }
  /** Exam Rush: questions from weak chapters plus the mistake notebook */
  | { kind: 'rush'; chapters: { subject: Subject; chapter: number }[]; ids: string[] };

/** Quick mini test: 15 questions in 10 minutes. */
export const QUICK = { count: 15, seconds: 600 };
export const CHAPTER_TEST_SIZE = 15;

/** Builds a test. `diff` limits questions to one difficulty level. */
export function buildTest(exam: Exam, spec: TestSpec = { kind: 'mixed' }, diff?: Difficulty): Question[] {
  if (spec.kind === 'subject') return sampleSubject(exam, spec.subject, 15, diff);
  if (spec.kind === 'chapter') {
    const pool = chapterQuestions(spec.subject, spec.chapter);
    const filtered = diff ? pool.filter((q) => q.difficulty === diff) : pool;
    return shuffle(filtered.length ? filtered : pool).slice(0, CHAPTER_TEST_SIZE);
  }
  if (spec.kind === 'ids') return shuffle(spec.ids.map(getQuestion).filter((q): q is Question => !!q)).slice(0, 20);
  if (spec.kind === 'rush') {
    const fromMistakes = shuffle(spec.ids.map(getQuestion).filter((q): q is Question => !!q)).slice(0, 10);
    const per = spec.chapters.length ? Math.ceil((20 - fromMistakes.length) / spec.chapters.length) : 0;
    const fromWeak = spec.chapters.flatMap((w) => shuffle(chapterQuestions(w.subject, w.chapter)).slice(0, per));
    const seen = new Set<string>();
    return shuffle([...fromMistakes, ...fromWeak].filter((q) => !seen.has(q.id) && !!seen.add(q.id))).slice(0, 20);
  }
  const subs = EXAMS[exam].subjects;
  if (spec.kind === 'quick') {
    const per = Math.ceil(QUICK.count / subs.length);
    return shuffle(subs.flatMap((s) => sampleSubject(exam, s, per, diff))).slice(0, QUICK.count);
  }
  return shuffle(subs.flatMap((s) => sampleSubject(exam, s, 4, diff)));
}

/** Correctness of one response. Numerical answers match within 1%. */
export function isCorrect(q: Question, a: Answer | undefined): boolean {
  if (a === undefined || a === -1 || a === '') return false;
  if (q.type === 'numerical') {
    const x = parseFloat(String(a));
    const y = parseFloat(q.numAnswer ?? '');
    return Number.isFinite(x) && Number.isFinite(y) && Math.abs(x - y) <= Math.max(0.01, Math.abs(y) * 0.01);
  }
  return a === q.answer;
}

export const isSkipped = (a: Answer | undefined) => a === -1 || a === '';

/** NTA marking: +4 correct, −1 wrong, 0 skipped. */
export function score(test: Question[], answers: (Answer | undefined)[]) {
  let correct = 0;
  let wrong = 0;
  answers.forEach((a, i) => {
    if (a === undefined || isSkipped(a)) return;
    if (isCorrect(test[i], a)) correct++;
    else wrong++;
  });
  return { correct, wrong, skipped: test.length - correct - wrong, marks: correct * 4 - wrong, max: test.length * 4 };
}

/** The correct answer as shown to the student, e.g. "B" or "42". */
export function answerLabel(q: Question): string {
  return q.type === 'numerical' ? String(q.numAnswer) : 'ABCD'[q.answer];
}

export function daysUntil(date: string): number {
  return Math.ceil((new Date(date + 'T09:00:00').getTime() - Date.now()) / 864e5);
}
